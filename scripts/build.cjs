// Bundles src/**/*.lua into the single-file plugin Studio users install.
const { readdirSync, readFileSync, statSync, writeFileSync } = require('node:fs');
const { join, relative } = require('node:path');

const root = join(__dirname, '..');
const srcDir = join(root, 'src');
const outFile = join(root, 'MoonHubBridge.plugin.lua');

function collect(dir) {
  return readdirSync(dir).sort().flatMap((entry) => {
    const path = join(dir, entry);
    return statSync(path).isDirectory() ? collect(path) : [path];
  });
}

function bundle() {
  const modules = collect(srcDir)
    .filter((path) => path.endsWith('.lua'))
    .map((path) => ({ name: relative(srcDir, path).replace(/\\/g, '/').replace(/\.lua$/, ''), source: readFileSync(path, 'utf8').trimEnd() }));
  if (!modules.some((module) => module.name === 'init')) throw new Error('src/init.lua is missing.');
  const parts = [
    '-- MoonHub Studio bridge. Allow HTTP requests in Studio settings before use.',
    '-- GENERATED by scripts/build.cjs from src/. Edit src/, then run `node scripts/build.cjs`.',
    'local definitions, loaded = {}, {}',
    'local function import(name)',
    '    if loaded[name] == nil then',
    '        local define = definitions[name]',
    '        if not define then error("Unknown module " .. name) end',
    '        loaded[name] = define()',
    '    end',
    '    return loaded[name]',
    'end',
  ];
  for (const module of modules) {
    parts.push('', `definitions["${module.name}"] = function()`, ...module.source.split('\n').map((line) => (line ? `    ${line}` : line)), 'end');
  }
  parts.push('', 'import("init")', '');
  return parts.join('\n');
}

const output = bundle();
if (process.argv.includes('--check')) {
  if (readFileSync(outFile, 'utf8') !== output) {
    console.error('MoonHubBridge.plugin.lua is stale. Run `node scripts/build.cjs`.');
    process.exit(1);
  }
} else {
  writeFileSync(outFile, output);
}
